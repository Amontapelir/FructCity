/* =====================================================================
   Кнопка «Печать» на листе сборки.

   Отдельным файлом, а не атрибутом onclick в разметке: политика
   безопасности (script-src 'self') блокирует любые инлайновые
   обработчики, и такая кнопка молча ничего не делала бы.
   ===================================================================== */
document.addEventListener('click', function (e) {
  const btn = e.target.closest && e.target.closest('[data-print]');
  if (btn) window.print();
});
